export function errorLabel(value) {
  if (!value) return "";
  const code = String(value).split(/[:\s]/)[0];
  return (
    errorLabels[code] ??
    (/[\u4e00-\u9fff]/.test(value) ? String(value) : "操作异常，请查看技术详情")
  );
}
export function technicalError(value) {
  return value ? `${errorLabel(value)}\n${value}` : "无错误";
}
